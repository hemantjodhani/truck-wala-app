#!/usr/bin/env node
/**
 * download-salon-songs.mjs
 * Downloads all songs from the barber shop playlist into public/songs/salon/
 * and generates src/data/salonSongs.js with the file manifest.
 *
 * Usage:
 *   node scripts/download-salon-songs.mjs
 *
 * Requires: yt-dlp installed and in PATH, ffmpeg installed
 */

import { execSync, spawnSync } from 'child_process';
import { existsSync, mkdirSync, readdirSync, writeFileSync, readFileSync } from 'fs';
import { join, basename } from 'path';
import { fileURLToPath } from 'url';
import { dirname } from 'path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const OUT_DIR = join(ROOT, 'public', 'songs', 'salon');
const MANIFEST_PATH = join(ROOT, 'src', 'data', 'salonSongs.js');

// YouTube Music playlist (same songs as the Spotify barber shop playlist)
const PLAYLIST_URL = 'https://music.youtube.com/playlist?list=PLTJ1PnzCWyFw';

console.log('🎵 Salon Song Downloader');
console.log('=========================');
console.log(`Output directory: ${OUT_DIR}`);
console.log(`Playlist: ${PLAYLIST_URL}`);
console.log('');

// Create output directory if it doesn't exist
if (!existsSync(OUT_DIR)) {
  mkdirSync(OUT_DIR, { recursive: true });
  console.log('✅ Created output directory');
}

// Download songs with yt-dlp
console.log('📥 Downloading songs (this may take a few minutes)...');
console.log('');

const ytdlpArgs = [
  PLAYLIST_URL,
  '--extract-audio',
  '--audio-format', 'mp3',
  '--audio-quality', '5',          // ~128kbps — small file size, good quality
  '--output', join(OUT_DIR, '%(playlist_index)02d - %(title)s.%(ext)s'),
  '--no-playlist-reverse',
  '--ignore-errors',               // skip unavailable songs
  '--no-warnings',
  '--progress',
  '--write-info-json',             // save metadata
  '--no-write-thumbnail',
  '--sleep-interval', '1',        // be polite to YouTube
];

const result = spawnSync('yt-dlp', ytdlpArgs, {
  stdio: 'inherit',
  shell: true,
  cwd: ROOT,
});

if (result.status !== 0 && result.status !== null) {
  console.error('⚠️  Some songs may have failed to download. Continuing with what we have...');
}

// Build the manifest from downloaded files
console.log('');
console.log('📋 Building song manifest...');

const files = readdirSync(OUT_DIR)
  .filter(f => f.endsWith('.mp3'))
  .sort();

if (!files.length) {
  console.error('❌ No MP3 files found in', OUT_DIR);
  process.exit(1);
}

const songs = files.map((filename) => {
  // Try to read metadata from info json
  const jsonFile = join(OUT_DIR, filename.replace('.mp3', '.info.json'));
  let title = filename.replace(/^\d+ - /, '').replace('.mp3', '');
  let artist = '';
  let durationSecs = 0;

  if (existsSync(jsonFile)) {
    try {
      const meta = JSON.parse(readFileSync(jsonFile, 'utf8'));
      title = meta.title || title;
      artist = meta.uploader || meta.channel || '';
      durationSecs = meta.duration || 0;
    } catch {}
  }

  const m = Math.floor(durationSecs / 60);
  const s = Math.floor(durationSecs % 60);
  const duration = durationSecs ? `${m}:${s.toString().padStart(2, '0')}` : '';

  return {
    title,
    artist,
    src: `/songs/salon/${filename}`,
    duration,
  };
});

// Write the manifest JS file
const manifestContent = `// Auto-generated by scripts/download-salon-songs.mjs
// ${songs.length} songs from the Barber Shop playlist
// DO NOT EDIT MANUALLY — re-run the script to update

export const SALON_SONGS = ${JSON.stringify(songs, null, 2)};
`;

writeFileSync(MANIFEST_PATH, manifestContent, 'utf8');

console.log(`✅ Generated manifest with ${songs.length} songs`);
console.log(`📄 Saved to: ${MANIFEST_PATH}`);
console.log('');
console.log('🎉 Done! Restart the dev server to load the songs.');
console.log('   The songs will appear in the Salon player automatically.');
